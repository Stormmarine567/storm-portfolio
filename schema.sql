-- STORM portfolio schema (Supabase / PostgreSQL)
-- Run this first in the Supabase SQL editor, then run seed.sql.

create table if not exists public.settings (
  id                  smallint primary key default 1 check (id = 1),
  brand_text          text not null default 'STORM',
  full_name           text not null default '',
  title               text not null default '',
  email               text not null default '',
  phone               text not null default '',
  location            text not null default '',
  github_url          text not null default '',
  linkedin_url        text not null default '',
  hero_image_url      text not null default '',
  portrait_image_url  text not null default '',
  secondary_image_url text not null default '',
  summary             text not null default '',
  accent_color        text not null default 'amber'
                      check (accent_color in ('amber','blue','green','purple','rose','cyan')),
  content             jsonb not null default '{}'::jsonb,
  stats               jsonb not null default '[]'::jsonb,
  testimonials        jsonb not null default '[]'::jsonb,
  updated_at          timestamptz not null default now()
);

create table if not exists public.projects (
  id               bigint generated by default as identity primary key,
  slug             text not null unique,
  title            text not null,
  subtitle         text not null default '',
  category         text not null default 'Fullstack',
  short_description text not null default '',
  card_description text not null default '',
  about            text not null default '',
  achievements     text not null default '',
  image_url        text not null default '',
  live_url         text not null default '',
  is_featured      boolean not null default true,
  sort_order       integer not null default 0,
  created_at       timestamptz not null default now()
);
create index if not exists projects_sort_idx on public.projects (sort_order);
create index if not exists projects_featured_idx on public.projects (is_featured);

create table if not exists public.experience (
  id          bigint generated by default as identity primary key,
  title       text not null,
  company     text not null,
  start_date  text not null,
  end_date    text not null default '',
  description text not null default '',
  bullets     jsonb not null default '[]'::jsonb,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now()
);
create index if not exists experience_sort_idx on public.experience (sort_order);

create table if not exists public.experience_projects (
  id            bigint generated by default as identity primary key,
  experience_id bigint not null references public.experience (id) on delete cascade,
  project_id    bigint not null references public.projects (id) on delete cascade,
  sort_order    integer not null default 0,
  unique (experience_id, project_id)
);
create index if not exists experience_projects_exp_idx on public.experience_projects (experience_id);
create index if not exists experience_projects_proj_idx on public.experience_projects (project_id);

create table if not exists public.skills (
  id         bigint generated by default as identity primary key,
  name       text not null,
  category   text not null default 'Core Skill'
             check (category in ('Core Skill','Tool / Technology','Language')),
  icon_url   text not null default '',
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists skills_category_idx on public.skills (category, sort_order);

create table if not exists public.education (
  id            bigint generated by default as identity primary key,
  institution   text not null,
  qualification text not null,
  year          text not null default '',
  sort_order    integer not null default 0,
  created_at    timestamptz not null default now()
);

create table if not exists public.messages (
  id         bigint generated by default as identity primary key,
  name       text not null,
  email      text not null,
  message    text not null,
  created_at timestamptz not null default now()
);
create index if not exists messages_created_idx on public.messages (created_at desc);

-- Row Level Security: no public access. The serverless functions use the
-- service_role key, which bypasses RLS, so only your API can read or write.
alter table public.settings            enable row level security;
alter table public.projects            enable row level security;
alter table public.experience          enable row level security;
alter table public.experience_projects enable row level security;
alter table public.skills              enable row level security;
alter table public.education           enable row level security;
alter table public.messages            enable row level security;

